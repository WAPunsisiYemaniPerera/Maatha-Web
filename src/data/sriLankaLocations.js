// Array of all 26 Districts
export const DISTRICTS = Object.keys(SRI_LANKA_LOCATIONS).sort();

// Helper to get all MOH areas for a specific district
export const getMohAreas = (district) => {
  if (!district || !SRI_LANKA_LOCATIONS[district]) return [];
  return SRI_LANKA_LOCATIONS[district];
};

// Helper to get a flat list of all unique MOH areas across the country
export const getAllMohAreas = () => {
  const allAreas = new Set();
  Object.values(SRI_LANKA_LOCATIONS).forEach(areas => {
    areas.forEach(area => allAreas.add(area));
  });
  return Array.from(allAreas).sort();
};

// Helper to find district by MOH area name
export const findDistrictByMohArea = (mohArea) => {
  if (!mohArea) return '';
  for (const [district, areas] of Object.entries(SRI_LANKA_LOCATIONS)) {
    if (areas.includes(mohArea)) {
      return district;
    }
  }
  return '';
};
